import logging
import uuid
from abc import ABC, abstractmethod

from config.settings import settings
from infrastructure.storage.client import upload_bytes

logger = logging.getLogger(__name__)


class ImageProvider(ABC):
    """Абстрактный провайдер генерации изображений."""

    @abstractmethod
    async def generate(self, prompt: str, width: int = 512, height: int = 512) -> bytes:
        """Сгенерировать изображение, вернуть байты."""
        ...

    @property
    @abstractmethod
    def name(self) -> str:
        ...


class RunwareProvider(ImageProvider):
    """Провайдер Runware."""

    name = "runware"

    async def generate(self, prompt: str, width: int = 512, height: int = 512) -> bytes:
        from runware import Runware, IImageInference
        import httpx

        runware = Runware(api_key=settings.runware_api_key)
        await runware.connect()

        request = IImageInference(
            positivePrompt=prompt,
            model="runware:100@1",  # FLUX schnell — быстрая бесплатная модель
            numberResults=1,
            width=width,
            height=height,
        )

        images = await runware.imageInference(requestImage=request)
        image_url = images[0].imageURL

        # Скачиваем изображение
        async with httpx.AsyncClient() as client:
            response = await client.get(image_url)
            response.raise_for_status()
            return response.content


class ImageRouter:
    """
    Роутер между провайдерами изображений.
    Пробует провайдеров по порядку, переключается при ошибке.
    """

    def __init__(self, providers: list[ImageProvider]):
        self.providers = providers

    async def generate(self, prompt: str, width: int = 512, height: int = 512) -> tuple[bytes, str]:
        """
        Сгенерировать изображение.
        Возвращает (байты, имя_провайдера).
        """
        last_error = None

        for provider in self.providers:
            try:
                logger.info(f"Trying image provider: {provider.name}")
                image_bytes = await provider.generate(prompt, width, height)
                return image_bytes, provider.name
            except Exception as e:
                logger.warning(f"Provider {provider.name} failed: {e}")
                last_error = e
                continue

        raise RuntimeError(f"All image providers failed. Last error: {last_error}")


def get_image_router() -> ImageRouter:
    """Создать роутер с доступными провайдерами."""
    providers = []

    if settings.runware_api_key:
        providers.append(RunwareProvider())

    if not providers:
        raise RuntimeError("No image providers configured. Set RUNWARE_API_KEY in .env")

    return ImageRouter(providers)


async def generate_and_upload(prompt: str, job_id: str) -> str:
    """
    Сгенерировать изображение и загрузить в Storage.
    Возвращает публичный URL.
    """
    router = get_image_router()
    image_bytes, provider_name = await router.generate(prompt)

    key = f"images/{job_id}.png"
    url = upload_bytes(key, image_bytes, content_type="image/png")

    logger.info(f"Image generated by {provider_name}, uploaded to {url}")
    return url